CREATE TYPE task_status AS ENUM ('planned', 'started', 'completed');

CREATE TYPE task_member_role AS ENUM ('owner', 'editor', 'viewer');

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_by_user_id BIGINT NOT NULL,
  name VARCHAR(255) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  priority INTEGER NOT NULL,
  status task_status NOT NULL DEFAULT 'planned',
  deadline TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_tasks_created_by_user
    FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE task_members (
  task_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  role task_member_role NOT NULL DEFAULT 'editor',
  added_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (task_id, user_id),
  CONSTRAINT fk_task_members_task
    FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
  CONSTRAINT fk_task_members_user
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE task_tags (
  task_id BIGINT NOT NULL,
  tag_id BIGINT NOT NULL,
  PRIMARY KEY (task_id, tag_id),
  CONSTRAINT fk_task_tags_task
    FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
  CONSTRAINT fk_task_tags_tag
    FOREIGN KEY (tag_id) REFERENCES tags (id) ON DELETE CASCADE
);

CREATE TABLE task_dependencies (
  task_id BIGINT NOT NULL,
  depends_on_task_id BIGINT NOT NULL,
  PRIMARY KEY (task_id, depends_on_task_id),
  CONSTRAINT chk_task_dependencies_not_self
    CHECK (task_id <> depends_on_task_id),
  CONSTRAINT fk_task_dependencies_task
    FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE RESTRICT,
  CONSTRAINT fk_task_dependencies_depends_on_task
    FOREIGN KEY (depends_on_task_id) REFERENCES tasks (id) ON DELETE RESTRICT
);

CREATE INDEX idx_tasks_created_by_user_id ON tasks (created_by_user_id);
CREATE INDEX idx_task_members_user_id ON task_members (user_id);
CREATE INDEX idx_task_tags_tag_id ON task_tags (tag_id);
CREATE INDEX idx_task_dependencies_depends_on_task_id
  ON task_dependencies (depends_on_task_id);

